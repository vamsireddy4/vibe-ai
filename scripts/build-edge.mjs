// Builds server/edge/: the Supabase Edge Functions the website calls, rewritten to run as Cloudflare
// Pages Functions (served at /fn/<name> by functions/fn/[name].ts). Runs before `vite build`.
// Only functions the app (src/) actually invokes are included, so provider webhooks (payments, inbound
// calls) are never exposed here by accident.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const SRC = "supabase/functions";
const OUT = "server/edge";
const SKIP = new Set(["_shared"]); // not routes
const NOT_PORTABLE = /Deno\.upgradeWebSocket|deno\.land\/std|npm:/; // websocket bridges etc. stay on Supabase
// Served only after a security review: these run with the service-role key, so every query must be
// scoped to the signed-in user. Reviewed 2026-11-04 (ownership checks added where missing).
const REVIEWED = new Set(`admin-dismiss-enterprise admin-grant-agency-access admin-list-agencies admin-list-clients
admin-revoke-agency-access admin-update-client-enterprise admin-update-client-spaces admin-upsert-agency-access agent-crm-data
book-calendar-appointment calendar-integrations-manage check-calendar-availability
create-google-doc-summary create-sms-template create-whatsapp-template delete-whatsapp-template
get-whatsapp-template-details ghl-oauth list-google-sheets
manage-calendar-booking phone-config-data phone-config-manage
run-gmail-campaign run-sms-campaign run-whatsapp-campaign send-campaign-messages send-sms-message
send-whatsapp-direct-message sms-campaign-data
sync-campaign-phone-configs sync-google-sheet sync-whatsapp-templates
upload-whatsapp-template-image validate-whatsapp-api-credentials voice-campaign-data voice-space-data`.split(/\s+/));

// Provider webhooks, ported even though the app never invokes them: Meta calls these (no Vibe AI sign-in).
// Served by their own route (functions/whatsapp-webhook/[[path]].ts), never at /fn/. Each checks its own secret.
const WEBHOOKS = new Set(["whatsapp-webhook"]); // keyed by the account's random webhook_key + 6-digit verify token

function appSources(dir, acc = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) appSources(p, acc);
    else if (/\.(tsx?)$/.test(f) && !f.includes(".test.")) acc.push(readFileSync(p, "utf8"));
  }
  return acc;
}
const app = appSources("src").join("\n");
const used = readdirSync(SRC)
  .filter((n) => !SKIP.has(n) && existsSync(join(SRC, n, "index.ts")))
  .filter((n) => new RegExp(`["'\`]${n}["'\`]`).test(app))
  .filter((n) => !NOT_PORTABLE.test(readFileSync(join(SRC, n, "index.ts"), "utf8")))
  .filter((n) => REVIEWED.has(n));
const webhooks = [...WEBHOOKS].filter((n) => existsSync(join(SRC, n, "index.ts")) && !NOT_PORTABLE.test(readFileSync(join(SRC, n, "index.ts"), "utf8")));

const shim = (file) => {
  const rel = relative(join(file, ".."), "server/edge-shim").replace(/\\/g, "/");
  return rel.startsWith(".") ? rel : `./${rel}`;
};
function port(code, file) {
  const out = code
    .replace(/from\s+["']https:\/\/esm\.sh\/@supabase\/supabase-js@2["']/g, `from "${shim(file)}"`)
    .replace(/Deno\.env\.get\(/g, "denoEnv(")
    .replace(/Deno\.serve\(/g, "export default (");
  if (/Deno\./.test(out)) throw new Error(`${file}: Deno API left after porting`);
  return (/denoEnv\(/.test(out) ? `import { denoEnv } from "${shim(file)}";\n` : "") + out;
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(join(OUT, "fns", "_shared"), { recursive: true });
for (const f of readdirSync(join(SRC, "_shared"))) {
  const file = join(OUT, "fns", "_shared", f);
  writeFileSync(file, port(readFileSync(join(SRC, "_shared", f), "utf8"), file));
}
for (const n of [...used, ...webhooks]) {
  const file = join(OUT, "fns", n, "index.ts");
  mkdirSync(join(OUT, "fns", n), { recursive: true });
  writeFileSync(file, port(readFileSync(join(SRC, n, "index.ts"), "utf8"), file));
}
writeFileSync(
  join(OUT, "registry.ts"),
  "// Generated by scripts/build-edge.mjs. Do not edit.\n" +
    `export const handlers: Record<string, () => Promise<{ default: (req: Request) => Response | Promise<Response> }>> = {\n${used
      .map((n) => `  "${n}": () => import("./fns/${n}/index.ts"),`)
      .join("\n")}\n};\n` +
    `export const webhooks: Record<string, () => Promise<{ default: (req: Request) => Response | Promise<Response> }>> = {\n${webhooks
      .map((n) => `  "${n}": () => import("./fns/${n}/index.ts"),`)
      .join("\n")}\n};\n`,
);
console.log(`edge functions ported: ${used.length} (+ webhooks: ${webhooks.join(", ") || "none"})`);
